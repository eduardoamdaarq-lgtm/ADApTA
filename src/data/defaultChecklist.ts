// Função geradora de novo projeto com baseline de checklist NBR 9050
export function createNewBuildingProject(
  building: BuildingData,
  sectors?: SectorDefinition[],
  templateMode: 'standard' | 'blank' = 'standard'
): InspectionProject {
  const newId = `adapta-proj-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
  const activeSectors = sectors && sectors.length > 0 ? sectors : PREESTABLISHED_SECTORS;
  
  // Gerar itens de vistoria baseados nos setores selecionados
  let items: InspectionItem[] = [];
  
  if (templateMode === 'standard') {
    // Mapeia os itens padrão que pertencem aos setores selecionados ou adapta para os novos setores
    items = INITIAL_INSPECTION_ITEMS.map((baseItem, index) => {
      // Se o setor do item base existe nos setores selecionados, mantém; caso contrário, vincula ao primeiro setor
      const matchingSector = activeSectors.find(s => s.id === baseItem.sectorId);
      const targetSector = matchingSector || activeSectors[0];
      
      return {
        ...baseItem,
        id: `${newId}-item-${index + 1}`,
        sectorId: targetSector.id,
        sectorName: targetSector.name,
        categoryId: targetSector.id,
        categoryName: targetSector.name,
        status: 'pendente',
        measurement: '',
        fieldNotes: '',
        criticality: 'Baixo',
        priorityGUT: 1,
        technicalDiagnosis: '',
        technicalRecommendation: '',
        suggestedDeadlineDays: undefined,
        photoUrl: undefined,
        location: `${targetSector.name}`,
      };
    });
  }

  const projectStatus = building.status || 'em_andamento';

  return {
    id: newId,
    building: {
      ...building,
      status: projectStatus,
    },
    sectors: activeSectors,
    items,
    status: projectStatus,
    scheduledDate: projectStatus === 'agendada' ? building.inspectionDate : undefined,
    completedDate: projectStatus === 'concluida' ? building.inspectionDate : undefined,
    laudoSummary: {
      executiveSummary: `Laudo Técnico Pericial de Acessibilidade da edificação ${building.name}, localizada em ${building.address}, ${building.city}/${building.state}. Enquadrada como ${building.classification === 'uso_publico' ? 'EDIFICAÇÃO DE USO PÚBLICO' : 'EDIFICAÇÃO DE USO COLETIVO'} (Decreto nº 5.296/2004).\n\nA vistoria técnica avaliou as condições arquitetônicas e urbanísticas em conformidade com as normas ABNT NBR 9050:2020 e ABNT NBR 16537.`,
      classification: 'Em Processamento de Vistoria',
      generalRecommendations: [
        'Concluir os registros de medição e evidências fotográficas dos setores vistoriados.',
        'Priorizar intervenções nos acessos principais, rotas de fuga e sanitários acessíveis.',
      ],
      technicalConclusion: 'Vistoria e levantamento pericial em andamento.',
      legalBasis: 'ABNT NBR 9050:2020, ABNT NBR 16537:2024, Lei Federal nº 13.146/2015 e Decreto nº 5.296/2004.',
      generatedAt: new Date().toISOString(),
    },
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}

